import fs from 'node:fs';
import path from 'node:path';
import type { AccessConfig } from './access.js';
import { SEGMENT_BYTES } from './seal.js';

/** Project root; this file compiles to dist/src/config.js. */
export const ROOT = path.resolve(import.meta.dirname, '..', '..');
export const CONFIG_PATH = path.join(ROOT, 'config.json');

const MiB = 1024 ** 2;
const GiB = 1024 ** 3;

export interface Config {
  host: string;
  port: number;
  /** "scrypt$N$salt$hash", produced by `npm run setup`. */
  passwordHash: string;
  /** Base32 TOTP secret, or null to disable the second factor. */
  totpSecret: string | null;
  /** Salt for the master encryption key (base64). Regenerated by `npm run setup`. */
  kdfSalt: string;
  /** Public salt the browser mixes into the passphrase key derivation (base64). */
  e2eeSalt: string;
  /** PBKDF2-SHA256 iterations the browser uses to derive the client-side key. */
  e2eeIterations: number;
  /** Refuse uploads that were not encrypted in the browser. */
  requireClientEncryption: boolean;
  /** Cloudflare Access JWT validation; null disables it (not recommended behind a tunnel). */
  access: AccessConfig | null;
  /** If non-empty, requests with any other Host header are refused. */
  allowedHosts: string[];
  /** Read the client IP from CF-Connecting-IP when the peer is loopback. */
  trustProxy: boolean;
  dataDir: string;
  maxFileBytes: number;
  maxTotalBytes: number;
  chunkBytes: number;
  defaultTtlSeconds: number;
  maxTtlSeconds: number;
  ttlChoices: number[];
  sessionIdleSeconds: number;
  sessionMaxSeconds: number;
  maxSessions: number;
  /** Write security events (never file names) to <dataDir>/audit.log. */
  auditLog: boolean;
}

export const DEFAULTS: Config = {
  host: '127.0.0.1',
  port: 8787,
  passwordHash: '',
  totpSecret: null,
  kdfSalt: '',
  e2eeSalt: '',
  e2eeIterations: 1_000_000,
  requireClientEncryption: true,
  access: null,
  allowedHosts: [],
  trustProxy: true,
  dataDir: 'data',
  maxFileBytes: 2 * GiB,
  maxTotalBytes: 10 * GiB,
  chunkBytes: 16 * MiB,
  defaultTtlSeconds: 3600,
  maxTtlSeconds: 24 * 3600,
  ttlChoices: [300, 900, 3600, 6 * 3600, 24 * 3600],
  sessionIdleSeconds: 900,
  sessionMaxSeconds: 8 * 3600,
  maxSessions: 3,
  auditLog: true,
};

type NumericKey =
  | 'port' | 'maxFileBytes' | 'maxTotalBytes' | 'chunkBytes'
  | 'defaultTtlSeconds' | 'maxTtlSeconds' | 'sessionIdleSeconds' | 'sessionMaxSeconds' | 'maxSessions' | 'e2eeIterations';

const POSITIVE_INT_KEYS: readonly NumericKey[] = [
  'port', 'maxFileBytes', 'maxTotalBytes', 'chunkBytes',
  'defaultTtlSeconds', 'maxTtlSeconds', 'sessionIdleSeconds', 'sessionMaxSeconds', 'maxSessions', 'e2eeIterations',
];

/** Reads the user-written config.json without applying defaults. */
export function loadRaw(configPath: string = CONFIG_PATH): Partial<Config> {
  if (!fs.existsSync(configPath)) return {};
  return JSON.parse(fs.readFileSync(configPath, 'utf8')) as Partial<Config>;
}

/** Applies defaults to a partial config and validates the result. */
export function resolve(raw: Partial<Config>): Config {
  const cfg: Config = { ...DEFAULTS, ...raw };
  if (!cfg.passwordHash) throw new Error('config.json: passwordHash is empty. Run "npm run setup".');

  for (const key of POSITIVE_INT_KEYS) {
    if (!Number.isSafeInteger(cfg[key]) || cfg[key] <= 0) {
      throw new Error(`config.json: "${key}" must be a positive integer`);
    }
  }
  if (!cfg.kdfSalt) throw new Error('config.json: kdfSalt is missing. Run "npm run setup".');
  if (!cfg.e2eeSalt) throw new Error('config.json: e2eeSalt is missing. Run "npm run setup".');
  if (cfg.chunkBytes % SEGMENT_BYTES !== 0) {
    throw new Error(`config.json: chunkBytes must be a multiple of ${SEGMENT_BYTES}`);
  }
  if (cfg.chunkBytes > 90 * MiB) {
    throw new Error('config.json: chunkBytes must stay under 90 MiB (Cloudflare caps request bodies at 100 MB)');
  }
  cfg.ttlChoices = [...new Set(cfg.ttlChoices)]
    .filter((s) => Number.isSafeInteger(s) && s > 0 && s <= cfg.maxTtlSeconds)
    .sort((a, b) => a - b);
  if (cfg.ttlChoices.length === 0) throw new Error('config.json: ttlChoices is empty after filtering');
  cfg.defaultTtlSeconds = Math.min(cfg.defaultTtlSeconds, cfg.maxTtlSeconds);
  cfg.allowedHosts = cfg.allowedHosts.map((h) => String(h).toLowerCase());
  cfg.dataDir = path.resolve(ROOT, cfg.dataDir);
  return cfg;
}

export function load(configPath: string = CONFIG_PATH): Config {
  if (!fs.existsSync(configPath)) throw new Error('config.json not found. Run "npm run setup" first.');
  return resolve(loadRaw(configPath));
}

export function save(raw: Partial<Config>, configPath: string = CONFIG_PATH): void {
  fs.writeFileSync(configPath, `${JSON.stringify(raw, null, 2)}\n`, { mode: 0o600 });
}
